import type { Listing } from '../types';
import { photo } from './photoLibrary';

const BASE = Date.parse('2026-09-13T09:00:00+08:00');

function daysAgo(days: number): string {
  return new Date(BASE - days * 24 * 60 * 60 * 1000).toISOString();
}

let seq = 0;
function nextId(): string {
  seq += 1;
  return `L${String(seq).padStart(4, '0')}`;
}

function makeListing(
  input: Omit<Listing, 'id' | 'createdAt' | 'updatedAt' | 'views'> & {
    createdDaysAgo: number;
    updatedDaysAgo?: number;
    views: number;
  },
): Listing {
  const { createdDaysAgo, updatedDaysAgo, ...rest } = input;
  return {
    id: nextId(),
    ...rest,
    createdAt: daysAgo(createdDaysAgo),
    updatedAt: daysAgo(updatedDaysAgo ?? createdDaysAgo),
  };
}

